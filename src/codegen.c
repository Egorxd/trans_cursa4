#include "ast.h"
#include <stdlib.h>
#include <string.h>

static void expression(FILE *out, Expr *e) {
    Link *link;
    switch (e->kind) {
    case EX_NUMBER: {
        char number[64];
        /* Emit the converted value: Python rejects decimal integers with leading zeros. */
        snprintf(number, sizeof(number), "%.17g", strtod(e->text, NULL));
        fputs(number, out);
        if (!strpbrk(number, ".eE")) fputs(".0", out);
        break;
    }
    case EX_VARIABLE: fprintf(out, "__v%zu", e->symbol); break;
    case EX_MATRIX:
        fputs("np.array([", out);
        for (link = e->items->head; link; link = link->next) {
            List *row = link->item;
            Link *cell;
            if (link != e->items->head) fputs(", ", out);
            fputc('[', out);
            for (cell = row->head; cell; cell = cell->next) {
                if (cell != row->head) fputs(", ", out);
                expression(out, cell->item);
            }
            fputc(']', out);
        }
        fputs("], dtype=np.float64)", out); break;
    case EX_UNARY:
        fprintf(out, "(%c", e->op); expression(out, e->left); fputc(')', out); break;
    case EX_BINARY:
        fputc('(', out); expression(out, e->left);
        fprintf(out, " %c ", e->op == '*' && e->type == TYPE_MATRIX ? '@' : e->op);
        expression(out, e->right); fputc(')', out); break;
    case EX_CALL:
        fprintf(out, "__%s(", e->text); expression(out, e->items->head->item);
        fprintf(out, ", %d, %d)", e->pos.line, e->pos.column); break;
    }
}
static void python_string(FILE *out, const char *text) {
    const unsigned char *p = (const unsigned char *)text;
    fputc('"', out);
    for (; *p; ++p) {
        if (*p == '\\' || *p == '"') fprintf(out, "\\%c", *p);
        else if (*p < 32 || *p == 127) fprintf(out, "\\x%02x", *p);
        else fputc(*p, out);
    }
    fputc('"', out);
}
